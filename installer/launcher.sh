#!/bin/bash
# BeamLink POS - macOS Launcher
# Starts MySQL, PHP, and Caddy, then opens the browser
# Works for both direct install and .app bundle

set -e

APP_NAME="BeamLink POS"

# Detect if running inside .app bundle or direct install
if [[ "$0" == *".app/Contents/MacOS/"* ]]; then
    # Inside .app bundle
    APP_BUNDLE="$(cd "$(dirname "$0")/.." && pwd)"
    INSTALL_DIR="$APP_BUNDLE/Resources"
else
    # Direct install / dev
    INSTALL_DIR="$(cd "$(dirname "$0")" && pwd)"
fi

# Writable user data directory (DB, logs, sessions, pids)
DATA_DIR="$HOME/.beamlink-pos"
LOG_DIR="$DATA_DIR/logs"
PID_DIR="$DATA_DIR/pids"
MYSQL_DIR="$INSTALL_DIR/mysql"
MYSQL_BIN="$MYSQL_DIR/bin"
PHP_DIR="$INSTALL_DIR/php"
CADDY_DIR="$INSTALL_DIR/caddy"
APP_DIR="$INSTALL_DIR/app"
PORT=8080

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

log() { echo -e "${GREEN}[$APP_NAME]${NC} $1"; }
warn() { echo -e "${YELLOW}[$APP_NAME]${NC} $1"; }
error() { echo -e "${RED}[$APP_NAME]${NC} $1"; exit 1; }

# Create directories
mkdir -p "$DATA_DIR" "$LOG_DIR" "$PID_DIR" "$DATA_DIR/sessions" "$DATA_DIR/stock"
mkdir -p "$APP_DIR/writable/cache" "$APP_DIR/writable/debugbar" "$APP_DIR/writable/logs" "$APP_DIR/writable/session" "$APP_DIR/writable/uploads" "$APP_DIR/writable/backup"
chmod -R 777 "$APP_DIR/writable" 2>/dev/null || true

# Check if already running
check_running() {
    if [ -f "$PID_DIR/mysql.pid" ]; then
        pid=$(cat "$PID_DIR/mysql.pid")
        if kill -0 "$pid" 2>/dev/null; then
            return 0
        fi
    fi
    return 1
}

if check_running; then
    warn "$APP_NAME is already running on port $PORT"
    open "http://localhost:$PORT"
    exit 0
fi

# Stop any existing instances
stop_all() {
    log "Stopping services..."
    # Stop Caddy
    if [ -f "$PID_DIR/caddy.pid" ]; then
        pid=$(cat "$PID_DIR/caddy.pid")
        kill "$pid" 2>/dev/null || true
        wait "$pid" 2>/dev/null || true
        rm -f "$PID_DIR/caddy.pid"
    fi
    # Kill PHP
    if [ -f "$PID_DIR/php.pid" ]; then
        pid=$(cat "$PID_DIR/php.pid")
        kill "$pid" 2>/dev/null || true
        wait "$pid" 2>/dev/null || true
        rm -f "$PID_DIR/php.pid"
    fi
    # Kill MySQL
    if [ -f "$PID_DIR/mysql.pid" ]; then
        pid=$(cat "$PID_DIR/mysql.pid")
        kill "$pid" 2>/dev/null || true
        wait "$pid" 2>/dev/null || true
        rm -f "$PID_DIR/mysql.pid"
    fi
}

trap stop_all EXIT INT TERM

# ============================================
# MYSQL
# ============================================

# Initialize MySQL if needed
if [ ! -d "$DATA_DIR/db" ] || [ ! -f "$DATA_DIR/db/ibdata1" ]; then
    log "Initializing database..."
    mkdir -p "$DATA_DIR/db"
    "$MYSQL_BIN/mysqld" \
        --initialize-insecure \
        --datadir="$DATA_DIR/db" \
        --user="$(whoami)" \
        --basedir="$MYSQL_DIR" \
        > "$LOG_DIR/install_db.log" 2>&1 || true
    log "Database initialized."
fi

# Set DB password for local POS instance
DB_PASS="pointofsale"

# Write my.cnf
cat > "$DATA_DIR/my.cnf" << EOF
[mysqld]
port=3307
basedir=$MYSQL_DIR
datadir=$DATA_DIR/db
socket=$DATA_DIR/mysql.sock
skip-name-resolve
innodb_buffer_pool_size=64M
innodb_log_file_size=8M
max_allowed_packet=64M
character-set-server=utf8mb4
collation-server=utf8mb4_general_ci
bind-address=127.0.0.1
mysqlx=OFF

[client]
port=3307
socket=$DATA_DIR/mysql.sock
default-character-set=utf8mb4
EOF

# Start MySQL
log "Starting MySQL on port 3307..."
"$MYSQL_BIN/mysqld" \
    --defaults-file="$DATA_DIR/my.cnf" \
    --console &
MYSQL_PID=$!
echo $MYSQL_PID > "$PID_DIR/mysql.pid"

# Wait for MySQL
log "Waiting for MySQL..."
for i in {1..30}; do
    if "$MYSQL_BIN/mysql" \
        --socket="$DATA_DIR/mysql.sock" \
        -u root \
        -e "SELECT 1" > /dev/null 2>&1; then
        break
    fi
    if [ $i -eq 30 ]; then
        error "MySQL failed to start. Check logs: $LOG_DIR/"
    fi
    sleep 1
done

# Create user and database
"$MYSQL_BIN/mysql" \
    --socket="$DATA_DIR/mysql.sock" \
    -u root << EOSQL
CREATE DATABASE IF NOT EXISTS ospos CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;
CREATE USER IF NOT EXISTS 'admin'@'127.0.0.1' IDENTIFIED BY '$DB_PASS';
CREATE USER IF NOT EXISTS 'admin'@'localhost' IDENTIFIED BY '$DB_PASS';
GRANT ALL PRIVILEGES ON ospos.* TO 'admin'@'127.0.0.1';
GRANT ALL PRIVILEGES ON ospos.* TO 'admin'@'localhost';
FLUSH PRIVILEGES;
EOSQL

log "MySQL ready."

# ============================================
# .env FILE
# ============================================

# CodeIgniter 4 configuration will be generated by the setup wizard.

# ============================================
# PHP
# ============================================

# Create php.ini
cat > "$DATA_DIR/php.ini" << EOF
memory_limit = 256M
max_execution_time = 300
upload_max_filesize = 100M
post_max_size = 100M
max_input_time = 300
error_reporting = E_ALL & ~E_NOTICE & ~E_STRICT & ~E_DEPRECATED
display_errors = Off
log_errors = On
error_log = $LOG_DIR/php_error.log
session.save_path = $DATA_DIR/sessions
date.timezone = Africa/Harare
extension=mysqli
extension=pdo_mysql
extension=gd
extension=zip
extension=mbstring
extension=curl
extension=openssl
extension=intl
extension=fileinfo
extension=bcmath
EOF

# Start PHP built-in server
log "Starting PHP server on port 9000..."
"$PHP_DIR/php" \
    -S 127.0.0.1:9000 \
    -t "$APP_DIR/public" \
    -c "$DATA_DIR/php.ini" \
    > "$LOG_DIR/php.log" 2>&1 &
PHP_PID=$!
echo $PHP_PID > "$PID_DIR/php.pid"
log "PHP ready."

# ============================================
# CADDY
# ============================================

# Write Caddyfile
cat > "$DATA_DIR/Caddyfile" << EOF
:8080 {
	reverse_proxy 127.0.0.1:9000
}
EOF

# Start Caddy
log "Starting Caddy on port $PORT..."
"$CADDY_DIR/caddy" start \
    --config "$DATA_DIR/Caddyfile" \
    --adapter caddyfile \
    > "$LOG_DIR/caddy.log" 2>&1 &
CADDY_PID=$!
echo $CADDY_PID > "$PID_DIR/caddy.pid"
log "Caddy ready."

# ============================================
# FIRST RUN CHECK
# ============================================

sleep 2

if [ ! -f "$DATA_DIR/.installed" ]; then
    log "First run - opening setup wizard..."
    open "http://localhost:$PORT/setup/" 2>/dev/null || osascript -e 'open location "http://localhost:8080/setup/"' 2>/dev/null || true
else
    log "$APP_NAME is running at http://localhost:$PORT"
    open "http://localhost:$PORT" 2>/dev/null || osascript -e 'open location "http://localhost:8080"' 2>/dev/null || true
fi

log "Press Ctrl+C to stop all services."
wait
